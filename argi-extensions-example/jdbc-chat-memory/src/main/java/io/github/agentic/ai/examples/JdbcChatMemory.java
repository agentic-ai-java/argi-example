package io.github.agentic.ai.examples;

import io.github.agentic.ai.memory.jdbc.H2ChatMemoryRepository;
import java.util.List;
import org.h2.jdbcx.JdbcDataSource;
import org.springframework.ai.chat.memory.MessageWindowChatMemory;
import org.springframework.ai.chat.messages.AssistantMessage;
import org.springframework.ai.chat.messages.Message;
import org.springframework.ai.chat.messages.UserMessage;
import org.springframework.jdbc.core.JdbcTemplate;

/** Stores a bounded Spring AI conversation using the Extensions JDBC repository. */
public final class JdbcChatMemory {

	private JdbcChatMemory() {
	}

	public static MessageWindowChatMemory memory(String url) {
		var source = new JdbcDataSource();
		source.setURL(url);
		var jdbc = new JdbcTemplate(source);
		// H2 folds unquoted identifiers to upper case; initialize the portable example
		// schema explicitly.
		jdbc.execute(
				"CREATE TABLE IF NOT EXISTS ai_chat_memory (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id VARCHAR(256), content CLOB, type VARCHAR(100), timestamp TIMESTAMP)");
		var repository = H2ChatMemoryRepository.h2Builder().jdbcTemplate(jdbc).build();
		return MessageWindowChatMemory.builder().chatMemoryRepository(repository).maxMessages(4).build();
	}

	public static List<Message> run(String url) {
		var memory = memory(url);
		memory.add("customer-42", new UserMessage("My preferred language is English."));
		memory.add("customer-42", new AssistantMessage("I will use English."));
		// A new facade reads persisted rows from the same database.
		return memory(url).get("customer-42");
	}

	public static void main(String[] args) {
		org.slf4j.LoggerFactory.getLogger(JdbcChatMemory.class)
			.info("{}", run("jdbc:h2:mem:chat;DB_CLOSE_DELAY=-1;DATABASE_TO_LOWER=TRUE"));
	}

}
